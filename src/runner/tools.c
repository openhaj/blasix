/**
 * @file tools.c
 * @brief lcrun spec tools: make fragment, probes, listings, lint, progress.
 * @Created: 2026/11/23 04:42:37 by Moutig
 * @Updated: 2026/11/24 03:17:02 by Moutig
 *
 *   --spec-make     variables for the Makefile: the feature-test macros
 *                   of the target, the units to build, the probes;
 *   --spec-probes   one tiny program per required interface. A probe
 *                   that does not compile means the header does not
 *                   declare it; one that compiles but does not link means
 *                   the library does not define it;
 *   --spec-list     every interface and what the target says about it;
 *   --spec-check    lint the database and the suites against it;
 *   --spec-matrix   per header, tested / required in each of the 8
 *                   standards (the progress of the suites);
 *   --spec-todo     what the target requires and no unit tests yet;
 *   --options       the option groups.
 */

