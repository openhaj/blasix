/** Feature macros for extension units and probes (glibc, musl, BSDs). */
#define EXT_DEFINES	"-D_DEFAULT_SOURCE -D_GNU_SOURCE -D_BSD_SOURCE"

const char	*kindName(t_kind k)
{
	static const char	*n[] = {
		[KIND_FUNC] = "function", [KIND_MACRO] = "macro", [KIND_TYPE] = "type",
		[KIND_EITHER] = "either", [KIND_VAR] = "var",
	};

	return (n[k]);
}

/**
 * @brief Is a probe of this kind also linked (the library must define it)?
 *
 * Functions, either and variables: yes. Macros and types: compiled only.
 *
 * @param k Kind.
 * @return 1 if linked, 0 otherwise.
 */
static int	kindLinks(t_kind k)
{
	return (k == KIND_FUNC || k == KIND_EITHER || k == KIND_VAR);
}

/* ----- --spec-make ----- */

int	toolMake(const t_run *r)
{
	char	buf[512];

	targetDescribe(&r->o.target, buf, sizeof(buf));
	printf("# generated by lcrun --spec-make: %s\n", buf);
	printf("LC_TARGET := %s\n", buf);
	targetCflags(&r->o.target, buf, sizeof(buf));
	printf("LC_STD_CFLAGS := %s\n", buf);
	printf("LC_EXT_CFLAGS := %s\n", EXT_DEFINES);
	printf("LC_UNITS :=");
	for (size_t i = 0; i < r->nUnits; i++)
		printf(" %s/%s", r->units[i].cat, r->units[i].func);
	printf("\nLC_EXT_UNITS :=");
	for (size_t i = 0; i < r->nUnits; i++)
	{
		int	ob;

		if (specRequired(r->units[i].entry, &r->o.target, &ob) == REQ_EXT)
			printf(" %s/%s", r->units[i].cat, r->units[i].func);
	}
	for (int pass = 0; pass < 2; pass++)
	{
		printf(pass ? "\nLC_PROBES_DECL :=" : "\nLC_PROBES_LINK :=");
		for (size_t i = 0; i < r->spec.n; i++)
		{
			const t_entry	*e = &r->spec.v[i];
			int				ob;

			if (!reqSelected(specRequired(e, &r->o.target, &ob)))
				continue ;
			if (kindLinks(e->kind) == !pass)
				printf(" %s/%s", e->cat, e->name);
		}
	}
	printf("\n");
	return (0);
}

/* ----- --spec-probes ----- */

/**
 * @brief mkdir -p.
 *
 * @param path Directory.
 * @return 0 (also if it exists), -1 on error.
 */
static int	mkdirs(const char *path)
{
	char	tmp[4096];

	snprintf(tmp, sizeof(tmp), "%s", path);
	for (char *p = tmp + 1; *p; p++)
	{
		if (*p != '/')
			continue ;
		*p = '\0';
		mkdir(tmp, 0755);
		*p = '/';
	}
	return (mkdir(tmp, 0755) == 0 || errno == EEXIST ? 0 : -1);
}

/**
 * @brief Write the main() of the probe of @p e, by kind.
 *
 *   - function: take the address of (name), which bypasses a
 *     function-like macro: the function itself must exist;
 *   - macro: #ifndef name fails;
 *   - type: declare a pointer to it;
 *   - var: take its address;
 *   - either: a macro is enough, otherwise take the address.
 *
 * @param fp Probe source.
 * @param e  Interface.
 */
static void	probeBody(FILE *fp, const t_entry *e)
{
	const char	*n = e->name;

	switch (e->kind)
	{
		case KIND_MACRO:
			fprintf(fp, "#ifndef %s\n# error \"%s is not defined as a macro\"\n#endif\n\n"
				"int\tmain(void)\n{\n\treturn (0);\n}\n", n, n);
			break ;
		case KIND_TYPE:
			fprintf(fp, "int\tmain(void)\n{\n\t%s\t*volatile p = 0;\n\n"
				"\t(void)p;\n\treturn (0);\n}\n", n);
			break ;
		case KIND_VAR:
			fprintf(fp, "int\tmain(void)\n{\n\tconst volatile void\t*p = "
				"(const void *)&(%s);\n\n\treturn (p == 0);\n}\n", n);
			break ;
		case KIND_EITHER:
			/* A macro is enough; otherwise the identifier must exist. */
			fprintf(fp, "int\tmain(void)\n{\n#ifndef %s\n\tconst volatile void\t*p = "
				"(const void *)&(%s);\n\n\treturn (p == 0);\n#else\n\treturn (0);\n"
				"#endif\n}\n", n, n);
			break ;
		default:
			/* (name) suppresses a function-like macro: the function itself */
			fprintf(fp, "int\tmain(void)\n{\n\tvoid\t(*volatile p)(void) = "
				"(void (*)(void))(%s);\n\n\treturn (p == 0);\n}\n", n);
	}
}

/**
 * @brief Check that the other headers of same= declare @p e the same way.
 *
 * Written after the first #include, before main(). What it captures from
 * the first header must still agree once every other header is
 * included, or the probe does not compile (reported as undeclared):
 *   - type: a typedef of it and an object declared with both types
 *     (two declarations of one object need compatible types);
 *   - macro: its value, which must then be an integer constant, is
 *     compared after the other headers;
 *   - function, either, var: a conflicting redeclaration in the other
 *     header is already a compile error.
 *
 * @param fp Probe source.
 * @param e  Interface with a same= tag.
 */
static void	probeSame(FILE *fp, const t_entry *e)
{
	char	buf[256];
	char	*save;

	if (e->kind == KIND_TYPE)
		fprintf(fp, "typedef %s\tlc_same_t;\n", e->name);
	else if (e->kind == KIND_MACRO)
		fprintf(fp, "enum { lc_same_v = (int)(%s) };\n", e->name);
	snprintf(buf, sizeof(buf), "%s", e->same);
	for (char *h = strtok_r(buf, ",", &save); h; h = strtok_r(NULL, ",", &save))
		fprintf(fp, "#include <%s>\n", h);
	if (e->kind == KIND_TYPE)
		fprintf(fp, "extern lc_same_t\tlc_same_o;\nextern %s\tlc_same_o;\n", e->name);
	else if (e->kind == KIND_MACRO)
		fprintf(fp, "typedef char\tlc_same_chk[(lc_same_v == (int)(%s)) ? 1 : -1];\n",
			e->name);
	fprintf(fp, "\n");
}

/**
 * @brief Write <dir>/<cat>/<name>.c, the probe of one interface.
 *
 * @param e   Interface.
 * @param ext 1 for an extension: the probe defines _GNU_SOURCE & co.
 * @param dir Probe directory.
 * @return 0, or -1 if the file cannot be written.
 */
static int	writeProbe(const t_entry *e, int ext, const char *dir)
{
	char	path[4096];
	FILE	*fp;

	snprintf(path, sizeof(path), "%s/%s", dir, e->cat);
	if (mkdirs(path) < 0)
		return (-1);
	snprintf(path, sizeof(path), "%s/%s/%s.c", dir, e->cat, e->name);
	fp = fopen(path, "w");
	if (fp == NULL)
		return (-1);
	fprintf(fp, "/* probe: %s %s, <%s>, since %s (%s:%d) */\n",
		kindName(e->kind), e->name, e->header, e->since, e->file, e->line);
	if (ext)
		fprintf(fp, "#define _DEFAULT_SOURCE\n#define _GNU_SOURCE\n#define _BSD_SOURCE\n");
	fprintf(fp, "#include <%s>\n\n", e->header);
	if (e->same)
		probeSame(fp, e);
	probeBody(fp, e);
	return (fclose(fp));
}

int	toolProbes(const t_run *r, const char *dir)
{
	int	n = 0;

	for (size_t i = 0; i < r->spec.n; i++)
	{
		const t_entry	*e = &r->spec.v[i];
		int				ob;
		t_req			q = specRequired(e, &r->o.target, &ob);

		if (!reqSelected(q))
			continue ;
		if (writeProbe(e, q == REQ_EXT, dir) < 0)
		{
			perror(dir);
			return (2);
		}
		n++;
	}
	fprintf(stderr, "lcrun: %d probes in %s\n", n, dir);
	return (0);
}

/* ----- --spec-list ----- */

/**
 * @brief Append the notes of one line to @p notes (base, ob, removed, ext).
 *
 * @param e     Line.
 * @param notes NUL-terminated buffer.
 * @param size  Size of @p notes.
 */
static void	lineNotes(const t_entry *e, char *notes, size_t size)
{
	size_t	len = strlen(notes);

	if (e->base && len < size)
		len += (size_t)snprintf(notes + len, size - len, "base in %s; ", e->base);
	if (e->ob && len < size)
		len += (size_t)snprintf(notes + len, size - len, "obsolescent in %s; ", e->ob);
	if (e->removed && len < size)
		len += (size_t)snprintf(notes + len, size - len, "removed in %s; ", e->removed);
	if (e->ext && len < size)
		snprintf(notes + len, size - len, "%s extension; ", e->ext);
}

int	toolList(const t_run *r)
{
	char	buf[512];
	int		count[REQ_EXT + 1] = {0};
	int		obs = 0;

	targetDescribe(&r->o.target, buf, sizeof(buf));
	printf("target: %s\n\n", buf);
	printf("%-12s %-26s %-8s %-13s %-8s %-11s %s\n", "category", "name",
		"kind", "since", "option", "target", "notes");
	for (size_t i = 0; i < r->spec.n; i++)
	{
		const t_entry	*e = &r->spec.v[i];
		int				ob;
		t_req			q = specRequired(e, &r->o.target, &ob);
		char			notes[512] = "";

		count[q]++;
		obs += ob;
		lineNotes(e, notes, sizeof(notes));
		if (e->alt)
		{
			size_t	len = strlen(notes);

			snprintf(notes + len, sizeof(notes) - len, "also %s%s%s; ", e->alt->since,
				e->alt->opt ? " " : "", e->alt->opt ? e->alt->opt : "");
			lineNotes(e->alt, notes, sizeof(notes));
		}
		if (!r->o.verbose && !reqSelected(q))
			continue ;
		printf("%-12s %-26s %-8s %-13s %-8s %-11s %s\n", e->cat, e->name,
			kindName(e->kind), e->since, e->opt ? e->opt : "-", reqName(q), notes);
	}
	printf("\n%d required (%d obsolescent), %d by options, %d extensions; "
		"excluded: %d not yet, %d removed, %d option off%s\n",
		count[REQ_BASE], obs, count[REQ_OPTION], count[REQ_EXT],
		count[REQ_NOT_YET], count[REQ_REMOVED], count[REQ_OPTION_OFF],
		r->o.verbose ? "" : " (-v lists them)");
	return (0);
}

/* ----- Units on disk, whatever the target ----- */

/**
 * @brief Is there a test file <suites>/<cat>/<name>.c?
 *
 * @param r Run (suites directory).
 * @param e Interface.
 * @return 1 if the unit exists, 0 otherwise.
 */
static int	hasUnit(const t_run *r, const t_entry *e)
{
	char		path[4096];
	struct stat	sb;

	snprintf(path, sizeof(path), "%s/%s/%s.c", r->o.suitesDir, e->cat, e->name);
	return (stat(path, &sb) == 0);
}

/* ----- --spec-check ----- */

/**
 * @brief Is @p since an ISO C edition?
 *
 * @param since Version.
 * @return 1 for C99 ... C23, 0 otherwise.
 */
static int	isCSince(const char *since)
{
	const t_std	*s = stdFind(since);

	return (s && s->posix == 0);
}

/**
 * @brief Lint one line: base= needs an option, no POSIX option on an ISO
 *        C line, same= lists other headers.
 *
 * @param e Line.
 * @return Number of errors (reported on stderr).
 */
static int	checkLine(const t_entry *e)
{
	const t_optdef	*d = e->opt ? optFind(e->opt) : NULL;
	int				errors = 0;

	if (e->base && !e->opt)
	{
		fprintf(stderr, "%s:%d: %s: base= without an option group\n",
			e->file, e->line, e->name);
		errors++;
	}
	if (d && d->from == NULL && isCSince(e->since))
	{
		fprintf(stderr, "%s:%d: %s: POSIX option %s on an ISO C line\n",
			e->file, e->line, e->name, e->opt);
		errors++;
	}
	if (e->same && (strstr(e->same, ".h") == NULL || strstr(e->same, e->header)))
	{
		fprintf(stderr, "%s:%d: %s: same= must list other headers (x.h,y.h)\n",
			e->file, e->line, e->name);
		errors++;
	}
	return (errors);
}

int	toolCheck(const t_run *r)
{
	DIR				*top;
	struct dirent	*c;
	char			path[4096];
	int				errors = r->spec.errors;
	int				units = 0;

	top = opendir(r->o.suitesDir);
	if (top == NULL)
	{
		perror(r->o.suitesDir);
		return (2);
	}
	while ((c = readdir(top)) != NULL)
	{
		DIR				*sub;
		struct dirent	*f;

		if (c->d_name[0] == '.')
			continue ;
		snprintf(path, sizeof(path), "%s/%s", r->o.suitesDir, c->d_name);
		sub = opendir(path);
		if (sub == NULL)
			continue ;
		while ((f = readdir(sub)) != NULL)
		{
			size_t			len = strlen(f->d_name);
			char			*func;
			const t_entry	*e;

			if (len < 3 || strcmp(f->d_name + len - 2, ".c"))
				continue ;
			func = xstrndup(f->d_name, len - 2);
			e = specFind(&r->spec, c->d_name, func);
			units++;
			if (e == NULL)
			{
				fprintf(stderr, "%s/%s: no entry `%s` in %s/%s.spec\n", path,
					f->d_name, func, r->o.specDir, c->d_name);
				errors++;
			}
			else if (e->kind == KIND_TYPE)
			{
				fprintf(stderr, "%s/%s: `%s` is a type: test it from the unit of a "
					"function that uses it\n", path, f->d_name, func);
				errors++;
			}
			free(func);
		}
		closedir(sub);
	}
	closedir(top);
	for (size_t i = 0; i < r->spec.n; i++)
	{
		errors += checkLine(&r->spec.v[i]);
		if (r->spec.v[i].alt)
			errors += checkLine(r->spec.v[i].alt);
	}
	printf("%zu interfaces, %d units, %d error%s\n", r->spec.n, units, errors,
		errors == 1 ? "" : "s");
	return (errors ? 1 : 0);
}

/* ----- --options ----- */

int	toolOptions(void)
{
	const t_optdef	*d;

	printf("%-16s %-6s %-5s %-36s %s\n", "option", "family", "from", "defines",
		"description");
	for (size_t i = 0; (d = optAt(i)) != NULL; i++)
		printf("%-16s %-6s %-5s %-36s %s\n", d->name, d->from ? "ISO C" : "POSIX",
			d->from ? d->from : "-", d->want ? d->want : "-", d->desc);
	printf("\nISO C options are conditional features: required before `from`,\n"
		"optional from it on. POSIX options exist on POSIX targets only.\n"
		"Select with OPTS=A,B (make) or -O A,B (lcrun); in a test, .opt = \"XSI\".\n");
	return (0);
}

/* ----- --spec-matrix ----- */

/** Columns of the matrix (the 8 standards). */
#define MAX_STDS	8

/**
 * @brief The run's target moved to standard @p s, keeping the options
 *        that make sense there (no POSIX option on an ISO C standard).
 *
 * @param r   Run.
 * @param s   Standard of the column.
 * @param buf Storage for the option list (64 entries).
 * @return The target.
 */
static t_target	targetFor(const t_run *r, const t_std *s, char **buf)
{
	t_target	t = r->o.target;
	size_t		n = 0;

	t.std = s;
	for (char **o = r->o.target.opts; o && *o && n < 63; o++)
	{
		const t_optdef	*d = optFind(*o);

		if (d == NULL || d->from || s->posix)
			buf[n++] = *o;
	}
	buf[n] = NULL;
	t.opts = buf;
	return (t);
}

/**
 * @brief Print one cell of the matrix: "tested/req", or "-" when nothing
 *        is required.
 *
 * @param tested Required interfaces with a unit.
 * @param req    Required interfaces.
 */
static void	cell(int tested, int req)
{
	char	c[24];

	if (req)
		snprintf(c, sizeof(c), "%d/%d", tested, req);
	else
		snprintf(c, sizeof(c), "-");
	printf(" %12s", c);
}

int	toolMatrix(const t_run *r)
{
	char		*optBuf[MAX_STDS][64];
	t_target	t[MAX_STDS];
	size_t		nStd = 0;
	int			total[MAX_STDS][2] = {{0}};
	char		buf[512];

	while (nStd < MAX_STDS && stdAt(nStd))
	{
		t[nStd] = targetFor(r, stdAt(nStd), optBuf[nStd]);
		nStd++;
	}
	targetDescribe(&r->o.target, buf, sizeof(buf));
	printf("tested / required per header, options of %s (ISO C columns: ISO C "
		"options only)\n\n%-14s", buf, "header");
	for (size_t s = 0; s < nStd; s++)
		printf(" %12s", stdAt(s)->name);
	printf("\n");
	for (size_t i = 0, j; i < r->spec.n; i = j)
	{
		int	row[MAX_STDS][2] = {{0}};

		for (j = i; j < r->spec.n && !strcmp(r->spec.v[j].cat, r->spec.v[i].cat); j++)
		{
			int	tested = hasUnit(r, &r->spec.v[j]);

			for (size_t s = 0; s < nStd; s++)
			{
				int	ob;

				if (!reqSelected(specRequired(&r->spec.v[j], &t[s], &ob)))
					continue ;
				row[s][1]++;
				row[s][0] += tested;
			}
		}
		if (!inList(r->o.cats, r->spec.v[i].cat))
			continue ;
		printf("%-14s", r->spec.v[i].cat);
		for (size_t s = 0; s < nStd; s++)
		{
			total[s][0] += row[s][0];
			total[s][1] += row[s][1];
			cell(row[s][0], row[s][1]);
		}
		printf("\n");
	}
	printf("%-14s", "TOTAL");
	for (size_t s = 0; s < nStd; s++)
		cell(total[s][0], total[s][1]);
	printf("\n");
	return (0);
}

/* ----- --spec-todo ----- */

int	toolTodo(const t_run *r)
{
	char	buf[512];
	int		todo = 0;
	int		req = 0;

	targetDescribe(&r->o.target, buf, sizeof(buf));
	printf("required by %s, no unit yet (%s/<cat>/<name>.c):\n", buf, r->o.suitesDir);
	for (size_t i = 0, j; i < r->spec.n; i = j)
	{
		int	shown = 0;

		for (j = i; j < r->spec.n && !strcmp(r->spec.v[j].cat, r->spec.v[i].cat); j++)
		{
			const t_entry	*e = &r->spec.v[j];
			int				ob;
			t_req			q = specRequired(e, &r->o.target, &ob);

			if (!reqSelected(q) || e->kind == KIND_TYPE || !inList(r->o.cats, e->cat))
				continue ;
			req++;
			if (hasUnit(r, e))
				continue ;
			if (!shown++)
				printf("\n  <%s>\n", e->header);
			printf("    %-28s %-8s %-13s %s%s\n", e->name, kindName(e->kind), e->since,
				q == REQ_OPTION ? (e->opt ? e->opt : e->alt->opt) : "",
				ob ? " (obsolescent)" : "");
			todo++;
		}
	}
	printf("\n%d of %d still to test (types are tested from the units that use them)\n",
		todo, req);
	return (0);
}
