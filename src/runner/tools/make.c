/**
 * @file make.c
 * @brief lcrun --spec-make: the make fragment of a target.
 * @Created: 2026/11/24 08:18:20 by Moutig
 * @Updated: 2026/11/24 08:24:14 by Moutig
 *
 * spec.mk: feature-test macros, units (source paths), probes (declared,
 * hidden, reject), the definitions of each category (LC_DEFS_<cat>).
 */

#include "runner/lcrun.h"

#include <ctype.h>
#include <errno.h>
#include <stddef.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>

/** Feature macros for extension units and probes (glibc, musl, BSDs). */
#define EXT_DEFINES	"-D_DEFAULT_SOURCE -D_GNU_SOURCE -D_BSD_SOURCE"

/**
 * @brief Is a probe of this kind also linked (the library must define it)?
 *
 * Functions, either and variables: yes. Macros and types: compiled only.
 *
 * @param k Kind.
 * @return 1 if linked, 0 otherwise.
 */
static int	kindLinks(t_kind k)
{
	return (k == KIND_FUNC || k == KIND_EITHER || k == KIND_VAR);
}

int	toolMake(const t_run *r)
{
	char	buf[512];

	targetDescribe(&r->o.target, buf, sizeof(buf));
	printf("# generated by lcrun --spec-make: %s\n", buf);
	printf("LC_TARGET := %s\n", buf);
	targetCflags(&r->o.target, buf, sizeof(buf));
	printf("LC_STD_CFLAGS := %s\n", buf);
	printf("LC_EXT_CFLAGS := %s\n", EXT_DEFINES);
	/* source paths: <cat>[/<group>...]/<func> (the bin/ layout) */
	printf("LC_UNITS :=");
	for (size_t i = 0; i < r->nUnits; i++)
		printf(" %s", r->units[i].rel);
	printf("\nLC_EXT_UNITS :=");
	for (size_t i = 0; i < r->nUnits; i++)
	{
		int	ob;

		if (r->units[i].entry
			&& specRequired(r->units[i].entry, &r->o.target, &ob) == REQ_EXT)
			printf(" %s", r->units[i].rel);
	}
	for (int pass = 0; pass < 2; pass++)
	{
		printf(pass ? "\nLC_PROBES_DECL :=" : "\nLC_PROBES_LINK :=");
		for (size_t i = 0; i < r->spec.n; i++)
		{
			const t_entry	*e = &r->spec.v[i];
			int				ob;

			if (!reqSelected(specRequired(e, &r->o.target, &ob)))
				continue ;
			if (kindLinks(e->kind) == !pass)
				printf(" %s/%s", e->cat, e->name);
		}
	}
	/* <cat>/defs: the types and macros the target requires (make turns
	   the declared ones into -DLC_REQ_<name>) */
	for (size_t i = 0; i < r->spec.n; i++)
	{
		const t_entry	*e = &r->spec.v[i];
		int				ob;

		if (i == 0 || strcmp(e->cat, r->spec.v[i - 1].cat))
			printf("\nLC_DEFS_%s :=", e->cat);
		if ((e->kind == KIND_TYPE || e->kind == KIND_MACRO)
			&& reqSelected(specRequired(e, &r->o.target, &ob)))
			printf(" %s", e->name);
	}
	/* Interfaces that must not be visible: empty in lax mode. */
	printf("\nLC_PROBES_HIDDEN :=");
	for (size_t i = 0; i < r->spec.n && !r->o.lax; i++)
	{
		const t_entry	*e = &r->spec.v[i];

		if (specVisibility(&r->spec, e, &r->o.target, NULL, NULL) == VIS_HIDDEN)
			printf(" %s/%s", e->cat, e->name);
	}
	/* Translation units that must not compile. */
	printf("\nLC_PROBES_REJECT :=");
	{
		t_reject	*rj;
		size_t		n = specRejects(&r->spec, &r->o.target, &rj);

		for (size_t i = 0; i < n; i++)
			printf(" %s/%s", rj[i].cat, rj[i].id);
		free(rj);
	}
	printf("\n");
	return (0);
}
